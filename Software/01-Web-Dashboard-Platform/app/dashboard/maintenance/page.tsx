"use client";

import Link from "next/link";
import { AlertTriangle, CheckCircle2 } from "lucide-react";
import { Card, CardContent, CardHeader, CardTitle, CardDescription } from "@/components/ui/card";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Progress } from "@/components/ui/progress";
import { useFleetStore } from "@/lib/store/fleetStore";

export default function MaintenancePage() {
  const awgProfiles = useFleetStore((s) => s.awgProfiles);
  const awgStates = useFleetStore((s) => s.awgStates);
  const alerts = useFleetStore((s) => s.alerts);
  const acknowledgeAlert = useFleetStore((s) => s.acknowledgeAlert);

  const sortedByHealth = [...awgStates].sort((a, b) => a.healthScore - b.healthScore);
  const unresolvedAlerts = alerts.filter((a) => !a.resolvedAtIso);

  return (
    <div className="space-y-6">
      <div>
        <h1 className="text-2xl font-semibold text-foreground">Predictive Maintenance &amp; Alerts</h1>
        <p className="text-sm text-muted-foreground">Health scores and alerts generated by the simulation — no real hardware is monitored.</p>
      </div>

      <Card>
        <CardHeader>
          <CardTitle className="text-base">Active alerts</CardTitle>
          <CardDescription>{unresolvedAlerts.length} unresolved</CardDescription>
        </CardHeader>
        <CardContent className="space-y-2">
          {unresolvedAlerts.length === 0 && (
            <p className="flex items-center gap-2 text-sm text-muted-foreground">
              <CheckCircle2 className="h-4 w-4 text-success" /> No active alerts.
            </p>
          )}
          {unresolvedAlerts.slice(0, 20).map((alert) => (
            <div key={alert.id} className="flex items-center justify-between gap-3 rounded-lg border border-border bg-secondary/30 p-3">
              <div className="flex items-start gap-2">
                <AlertTriangle
                  className={`mt-0.5 h-4 w-4 ${alert.severity === "critical" ? "text-critical" : alert.severity === "warning" ? "text-warning" : "text-muted-foreground"}`}
                />
                <div>
                  <p className="text-sm text-foreground">{alert.message}</p>
                  <p className="text-xs text-muted-foreground">
                    {alert.equipmentId} · {alert.type} {alert.acknowledgedAtIso && "· acknowledged"}
                  </p>
                </div>
              </div>
              {!alert.acknowledgedAtIso && (
                <Button size="sm" variant="outline" onClick={() => acknowledgeAlert(alert.id)}>
                  Acknowledge
                </Button>
              )}
            </div>
          ))}
        </CardContent>
      </Card>

      <Card>
        <CardHeader>
          <CardTitle className="text-base">Equipment health (lowest first)</CardTitle>
        </CardHeader>
        <CardContent className="space-y-2">
          {sortedByHealth.map((state) => {
            const profile = awgProfiles.find((p) => p.id === state.id);
            return (
              <Link
                key={state.id}
                href={`/dashboard/awg/${state.id}`}
                className="flex items-center justify-between gap-4 rounded-lg border border-border bg-secondary/30 p-3 hover:bg-secondary/60"
              >
                <div className="flex-1">
                  <div className="flex items-center justify-between text-sm">
                    <span className="font-medium text-foreground">{profile?.name ?? state.id}</span>
                    <span className="font-mono text-muted-foreground">{state.healthScore.toFixed(0)}/100</span>
                  </div>
                  <Progress value={state.healthScore} className="mt-1" />
                </div>
                <Badge variant={state.healthStatus === "nominal" ? "outline" : "destructive"}>{state.healthStatus}</Badge>
              </Link>
            );
          })}
        </CardContent>
      </Card>
    </div>
  );
}
